#!/usr/bin/env python3
# lab_3.2/imu/tmp/position_*.csv -> lab_3.2/imu/position_csv.h
# the pico writes them onto the sd card itself, no card reader needed.
import pathlib

IMU = pathlib.Path(__file__).resolve().parents[2] / "lab_3.2" / "imu"

files = sorted((IMU / "tmp").glob("position_*.csv"))
lines = ["// generated by notebook/lab_3_2/csv_header.py from tmp/position_*.csv", "#pragma once", ""]
for f in files:
    lines.append(f'static const char {f.stem.upper()}_CSV[] = R"csv({f.read_text()})csv";')
lines.append("")
lines.append("static const char* const POSITION_CSV[] = {" + ", ".join(f"{f.stem.upper()}_CSV" for f in files) + "};")
(IMU / "position_csv.h").write_text("\n".join(lines) + "\n")
print(f"{len(files)} files -> {IMU / 'position_csv.h'}")
